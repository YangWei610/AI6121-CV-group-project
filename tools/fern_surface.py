def fern_foreground(aligned, frame, views, state, use_silhouettes):
    keep = np.all((aligned >= ROI_MIN) & (aligned <= ROI_MAX), axis=1)
    if use_silhouettes:
        world = aligned[keep] @ frame.rotation + frame.center
        keep[keep] = silhouette_mask(
            world, views, state, polygons={("006", frame): points for frame, points in SILHOUETTES.items()},
            thumbnail_size=THUMBNAIL_SIZE, minimum_votes=7,
        )
    return keep


def front_display(frame, aligned_vertices, state):
    """Match the saved front keyframe's horizontal and vertical directions."""
    reference = state.cam_R[state.registered_cams[0]]
    rotation = np.vstack((reference[0], reference[2], -reference[1]))
    world = aligned_vertices @ frame.rotation + frame.center
    rotated = world @ rotation.T
    lower, upper = np.percentile(rotated, [1, 99], axis=0)
    center = ((lower + upper) / 2) @ rotation
    extent = np.maximum((upper - lower) / 2, 1e-6)
    return PointCloudRenderFrame(center, rotation, extent, extent.copy())


def main():
    args = parse_surface_args(__doc__, FINAL, EXPERIMENT, 0.065, default_output=FINAL / "surface_006")
    reconstruct_surface(
        args, experiment=EXPERIMENT, object_name="fern", bounds=(ROI_MIN, ROI_MAX),
        mask_points=fern_foreground, silhouette_count=len(SILHOUETTES),
        align_for_display=front_display,
    )


if __name__ == "__main__":
    main()
